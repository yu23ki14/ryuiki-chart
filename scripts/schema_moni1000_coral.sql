-- モニタリングサイト1000 サンゴ礁調査（SAN01）の奄美分（scripts/m11_moni1000_coral.py が作る）。
-- 設計: docs/plans/MONI1000.md §9。種の出現ではなく、地点（スポット）×年度の観測値なので moni1000_counts とは別表。
-- occurrence にも observation にも流さない。get_records(record_set=coral_reef_surveys) が全行を返す。
-- 値は原文の文字列（'<5'・'-'・'20-30' 等）を *_raw にそのまま持ち、数値に直せたものだけを数値列に入れる（直せないものは NULL）。
-- 緯度経度は度分秒（lat_dms_raw / lon_dms_raw に原文）から十進の度に換算した値。
CREATE TABLE IF NOT EXISTS moni1000_coral_spots (
  record_id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  source_ref TEXT,
  fiscal_year INTEGER NOT NULL,
  block_ja TEXT,
  site_no INTEGER NOT NULL,
  site_name_ja TEXT,
  spot_no INTEGER NOT NULL,
  spot_name_ja TEXT,
  prefecture_ja TEXT,
  lat REAL,
  lon REAL,
  lat_dms_raw TEXT,
  lon_dms_raw TEXT,
  landform_ja TEXT,
  substrate_ja TEXT,
  area_m_raw TEXT,
  depth_range_m_raw TEXT,
  observed_on TEXT,
  investigator_ja TEXT,
  method TEXT,
  observe_minutes_raw TEXT,
  observe_minutes REAL,
  cover_pct_raw TEXT,
  cover_pct REAL,
  bleach_all_pct_raw TEXT,
  bleach_all_pct REAL,
  bleach_acropora_pct_raw TEXT,
  bleach_acropora_pct REAL,
  dead_all_pct_raw TEXT,
  dead_all_pct REAL,
  dead_acropora_pct_raw TEXT,
  dead_acropora_pct REAL,
  recruits_per_m2_raw TEXT,
  recruits_per_m2 REAL,
  table_acropora_size_cm_raw TEXT,
  table_acropora_size_cm REAL,
  cots_per_15min_raw TEXT,
  cots_per_15min REAL,
  cots_dominant_size_cm_raw TEXT,
  cots_dominant_size_cm REAL,
  cots_predation_pct_raw TEXT,
  cots_predation_pct REAL,
  snail_predation_pct_raw TEXT,
  snail_predation_pct REAL,
  spss_kg_m3_raw TEXT,
  spss_kg_m3 REAL,
  grouper_n_raw TEXT,
  grouper_n REAL,
  wrasse_n_raw TEXT,
  wrasse_n REAL,
  parrotfish_n_raw TEXT,
  parrotfish_n REAL,
  growth_class TEXT,
  growth_type_ja TEXT,
  cots_class TEXT,
  cots_size_range_cm TEXT,
  snail_class TEXT,
  spss_class TEXT,
  disease TEXT,
  note_ja TEXT
);
CREATE INDEX IF NOT EXISTS ix_coral_src ON moni1000_coral_spots(source_id, fiscal_year);
